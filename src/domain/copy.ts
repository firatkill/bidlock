// PRD §9.2–§9.4. Template values are formatted by domain display helpers.
export function fillCopy(
  template: string,
  values: Record<string, string | number>,
): string {
  return template.replace(/\{([^}]+)\}/g, (token, key: string) =>
    values[key] === undefined ? token : String(values[key]),
  );
}
